import assert from 'node:assert/strict';
import {solvedStickerCube,applyMoveToken,toCubieState} from '../cube/sticker-cube.mjs';
import {buildCrossPDB,indexOfFourEdges,FACE_EDGE_IDS} from '../cuberev-013/cross4-pdb.mjs';
import {FIVE_EDGE_STATES,fiveEdgeCoordinate,fourEdgeProjection,sixteenLiftsOfFour} from './five-edge-fiber.mjs';
const state=w=>{
 const c=solvedStickerCube();for(const m of w)applyMoveToken(c,m);
 return toCubieState(c);
};
const e=state([]),u=state(['U']);
assert.equal(FIVE_EDGE_STATES,3041280);
assert.equal(fourEdgeProjection(e.ep,e.eo),69760);
assert.equal(fourEdgeProjection(u.ep,u.eo),69760);
assert.equal(fiveEdgeCoordinate(e.ep,e.eo),1116160);
assert.equal(fiveEdgeCoordinate(u.ep,u.eo),1116192);
assert.deepEqual(sixteenLiftsOfFour([4,5,6,7],0).length,16);
const word=['F',"U'",'F','U','F','U','F',"U'","F'","U'",'F2'];
const v=state(word);
assert.equal(fiveEdgeCoordinate(v.ep,v.eo),fiveEdgeCoordinate(e.ep,e.eo));
assert.equal(fourEdgeProjection(v.ep,v.eo),fourEdgeProjection(e.ep,e.eo));
assert.deepEqual([v.ep[1],v.ep[2],v.ep[3]],[2,3,1]);
const table=buildCrossPDB('U');
const crossValue=c=>table.distances[indexOfFourEdges(c.ep,c.eo,FACE_EDGE_IDS.U)];
assert.equal(crossValue(e),0);
assert.equal(crossValue(u),1);
assert.equal(crossValue(v),5);
assert.equal(table.diameter,8);
assert.throws(()=>fiveEdgeCoordinate([0,1],[]),/FULL_EDGE/);
assert.throws(()=>sixteenLiftsOfFour([4,4,6,7],0),/BAD_FOUR/);
console.log('CUBE_REV_015_P3B_FIVE_EDGE_AND_U_CROSS_WITNESS_PASS');
