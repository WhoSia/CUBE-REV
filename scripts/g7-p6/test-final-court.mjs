import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import {spawnSync} from "node:child_process";
const d=fs.mkdtempSync(path.join(os.tmpdir(),"g7-p6-final-"));
const p=spawnSync(process.execPath,["scripts/g7-p6/evaluate-final-court.mjs",d],{encoding:"utf8"});
if(p.status!==0) throw new Error(p.stderr||p.stdout);
const r=JSON.parse(fs.readFileSync(path.join(d,"G7-P6-FINAL-COURT.json"),"utf8"));
if(r.verdict!=="HOLD_WORLD_CONTACT_OR_IDENTIFICATION_INSUFFICIENT") throw new Error("VERDICT");
if(!r.phase_closed||!r.next_phase_permission||r.mechanism_promotion) throw new Error("BOUNDARY");
console.log("G7_P6_FINAL_COURT_TEST_PASS");
