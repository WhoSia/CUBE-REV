import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import {spawnSync} from "node:child_process";
const d=fs.mkdtempSync(path.join(os.tmpdir(),"g7-p5-analysis-"));
let p=spawnSync("cargo",["run","-q","-p","search-geometry-core","--bin","g7_p5_packet_generator"],{encoding:"utf8"});
if(p.status!==0) throw new Error(p.stderr||p.stdout);
fs.writeFileSync(path.join(d,"packet.tsv"),p.stdout);
p=spawnSync(process.execPath,["scripts/g7-p5/compile-packet.mjs",path.join(d,"packet.tsv"),path.join(d,"packet.json")],{encoding:"utf8"});
if(p.status!==0) throw new Error(p.stderr||p.stdout);
p=spawnSync(process.execPath,["scripts/g7-p5/synthesize-events.mjs",path.join(d,"packet.json"),path.join(d,"events.jsonl")],{encoding:"utf8"});
if(p.status!==0) throw new Error(p.stderr||p.stdout);
p=spawnSync("python3",["scripts/g7-p5/analyze.py","--packet",path.join(d,"packet.json"),"--events",path.join(d,"events.jsonl"),"--out",path.join(d,"analysis"),"--permutations","2000"],{encoding:"utf8"});
if(p.status!==0) throw new Error(p.stderr||p.stdout);
const r=JSON.parse(fs.readFileSync(path.join(d,"analysis","analysis.json"),"utf8"));
if(r.authority!=="SYNTHETIC_VALIDATION_ONLY") throw new Error("AUTHORITY");
if(r.sessions!==8||r.valid_choice_rows!==192) throw new Error("SIZE");
if(!(r.primary.h3_agreement_rate>r.primary.h1_agreement_rate)) throw new Error("SYNTHETIC_SIGNAL");
console.log("G7_P5_ANALYSIS_TEST_PASS");
