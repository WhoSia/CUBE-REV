import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import {spawnSync} from "node:child_process";
const d=fs.mkdtempSync(path.join(os.tmpdir(),"g7-p5-sens-"));
const out=path.join(d,"s.json");
const p=spawnSync("python3",["scripts/g7-p5/sensitivity.py","--out",out,"--reps","800"],{encoding:"utf8"});
if(p.status!==0) throw new Error(p.stderr||p.stdout);
const r=JSON.parse(fs.readFileSync(out,"utf8"));
if(r.authority!=="DESIGN_CALIBRATION_ONLY"||r.frozen_complete_session_target!==24) throw new Error("AUTH");
const a=r.table.find(x=>x.complete_sessions===12&&x.signed_agreement_delta===0.10).sensitivity;
const b=r.table.find(x=>x.complete_sessions===40&&x.signed_agreement_delta===0.10).sensitivity;
if(!(b>a)) throw new Error("MONOTONIC_SIGNAL");
console.log("G7_P5_SENSITIVITY_TEST_PASS");
