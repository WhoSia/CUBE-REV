import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import {spawnSync} from "node:child_process";
import {verifyPacketBrowser,trialOrder} from "../../g7/p5/web/browser-core.mjs";
const d=fs.mkdtempSync(path.join(os.tmpdir(),"g7-p5-web-"));
let p=spawnSync("cargo",["run","-q","-p","search-geometry-core","--bin","g7_p5_packet_generator"],{encoding:"utf8"});
if(p.status!==0) throw new Error(p.stderr||p.stdout);
fs.writeFileSync(path.join(d,"packet.tsv"),p.stdout);
p=spawnSync(process.execPath,["scripts/g7-p5/compile-packet.mjs",path.join(d,"packet.tsv"),path.join(d,"packet.json")],{encoding:"utf8"});
if(p.status!==0) throw new Error(p.stderr||p.stdout);
const packet=JSON.parse(fs.readFileSync(path.join(d,"packet.json"),"utf8"));
await verifyPacketBrowser(packet);
const a=await trialOrder(packet,"VALIDATION-X"), b=await trialOrder(packet,"VALIDATION-X");
if(a.length!==24) throw new Error("TRIAL_COUNT");
if(a.map(x=>x.trial_id).join(",")!==b.map(x=>x.trial_id).join(",")) throw new Error("NONDETERMINISTIC_ORDER");
const html=fs.readFileSync("g7/p5/web/index.html","utf8");
if(!html.includes("Validation mode only")) throw new Error("MODE_BANNER");
console.log("G7_P5_BROWSER_CORE_TEST_PASS");
