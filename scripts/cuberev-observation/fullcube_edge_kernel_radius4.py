#!/usr/bin/env python3
"""Exact edge-only information horizon for full 54-facelet Rubik's Cube.

All full cube states in solved-ball B4 are generated by legal 18 HTM
turns (0..4 shell sizes 1,18,243,3240,43239). Each state is projected
onto the position+orientation of ALL 12 original tagged edge cubies.
A nontrivial common fiber in B4 prevents any adaptive full-cube solve,
even when observing all twelve edge orientation bits indefinitely.

The resulting group kernel has minimal nontrivial HTM word length EIGHT:
B3 is injective, and no B4 state collides with B3 (excludes length<=7
by balanced factorization), while the concrete 8-move corner-only
commutator U L U' R U L' U' R' fixes every edge.

Known classical group-theoretic phenomena; not scholarly-first claim.
"""
from __future__ import annotations
import collections,hashlib,itertools,json
from fullcube_goal_info_conflict import A,F,N,EDGES,physical_cube

PERMS,EDGE_SLOTS=physical_cube()
START=''.join(f*9 for f in F)
INVERSE=[]
for p in PERMS:
    inv=[None]*54
    for i,j in enumerate(p):inv[j]=i
    INVERSE.append(tuple(inv))
def turn(state,a):
    i=A.index(a) if isinstance(a,str) else a
    return ''.join(state[x] for x in INVERSE[i])
def apply(word):
    s=START
    for m in word:s=turn(s,m)
    return s

TAG_MAP={frozenset(e):i for i,e in enumerate(EDGES)}
def edge_vector(s):
    out=[255]*12
    for pos,(i,j) in enumerate(EDGE_SLOTS):
        a,b=s[i],s[j]
        tag=TAG_MAP[frozenset((a,b))]
        out[tag]=2*pos+(a!=EDGES[tag][0])
    assert sorted(out)==list(sorted(out)) and 255 not in out
    return bytes(out)

def corner_positions():
    slots=[]
    for f in F:
        n=N[f];row=[]
        for x in (-1,0,1):
            for y in (-1,0,1):
                p=(n[0],x,y) if n[0] else ((x,n[1],y) if n[1] else (x,y,n[2]))
                row.append((p,n))
        row.sort(key=lambda q:','.join(map(str,q[0])))
        slots+=row
    positions=sorted({p for p,n in slots if all(abs(t)==1 for t in p)})
    return [tuple(i for i,(p,n) in enumerate(slots) if p==q) for q in positions]
CORNERS=corner_positions()
CORNER_IDS={frozenset(START[i] for i in slot):j for j,slot in enumerate(CORNERS)}
def corner_vector(s):
    result=[None]*8
    for dest,indices in enumerate(CORNERS):
        labels=tuple(s[i] for i in indices)
        tag=CORNER_IDS[frozenset(labels)]
        result[tag]=(dest,labels)
    return tuple(result)

def audit():
    visited={START:()}
    layers=[[START]]
    for depth in range(1,5):
        after=[]
        for s in layers[-1]:
            for a in range(18):
                t=turn(s,a)
                if t not in visited:
                    visited[t]=visited[s]+(a,)
                    after.append(t)
        layers.append(after)
    assert list(map(len,layers))==[1,18,243,3240,43239]
    full=collections.defaultdict(list)
    early={};cross=0
    for depth,layer in enumerate(layers):
        for s in layer:
            f=edge_vector(s)
            if depth<=3:
                assert f not in early
                early[f]=s
            elif f in early:
                cross+=1
            full[f].append(s)
    assert len(early)==3502 and cross==0
    duplicates=[v for v in full.values() if len(v)>1]
    assert len(full)==46309 and len(duplicates)==432
    assert all(len(v)==2 for v in duplicates)
    for v in duplicates:
        assert all(len(visited[s])==4 for s in v)
    supports=collections.Counter();pairs=[]
    for a,b in duplicates:
        x,y=corner_vector(a),corner_vector(b)
        moved=tuple(i for i in range(8) if x[i]!=y[i])
        assert len(moved)==3
        supports[moved]+=1
        pairs.append({'a':[A[i] for i in visited[a]],
                      'b':[A[i] for i in visited[b]],
                      'corner_support':list(moved)})
    assert len(supports)==56
    assert set(supports)==set(itertools.combinations(range(8),3))
    assert sum(supports.values())==432
    fixes=[tags for tags in itertools.combinations(range(8),6)
           if all(set(tags).intersection(c) for c in supports)]
    assert len(fixes)==28
    pair_a=apply(['U','L',"U'",'R'])
    pair_b=apply(['R','U','L',"U'"])
    comm=apply(['U','L',"U'",'R','U',"L'","U'","R'"])
    assert pair_a!=pair_b and edge_vector(pair_a)==edge_vector(pair_b)
    assert comm!=START and edge_vector(comm)==edge_vector(START)
    payload=json.dumps(pairs,sort_keys=True,separators=(',',':'))
    return {'status':'EXACT_FULL54_ALL_EDGE_SENSOR_KERNEL_RADIUS4_PASS',
       'physical_ball_sizes':[1,18,243,3240,43239],
       'states_radius_le4':46741,
       'distinct_all_twelve_edge_factor_signatures':len(full),
       'radius_le3_signatures':3502,
       'radius_le3_vs_depth4_collisions':0,
       'radius4_colliding_pairs':432,
       'all_collision_classes_exactly_two':True,
       'every_collision_moves_exactly_three_corners':True,
       'all_56_corner_support_triples_occur':True,
       'minimum_additional_tagged_corners_given_all12_edges':6,
       'number_of_sufficient_six_corner_choices':28,
       'shortest_nonidentity_all_edge_fixed_word_HTM':8,
       'explicit_eight_turn_commutator':['U','L',"U'",'R','U',"L'","U'","R'"],
       'distinct_radius4_colliding_scrambles':[
           ['U','L',"U'",'R'],['R','U','L',"U'"]],
       'all_432_pair_receipt_sha256':hashlib.sha256(payload.encode()).hexdigest(),
       'global_goal_solvability_radius_limit_edge_only':3,
       'noiseless_observation_and_unrestricted_contingent_moves':True}
if __name__=='__main__':
    print(json.dumps(audit(),sort_keys=True,indent=2))
