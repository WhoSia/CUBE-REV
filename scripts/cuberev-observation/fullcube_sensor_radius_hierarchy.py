#!/usr/bin/env python3
"""Exact min sensor counts on complete full-cube solved balls r=1,2,3.

Physical input: original CUBE-REV 0.24 whole 54-sticker geometry and 18 HTM
action permutations. A sensor returns the orientation bit of one ORIGINAL
tagged edge cubie after each turn. Full-cube goal is all 54 stickers solved.

Mathematical certification:
1. Every source state within radius r is generated by exact physical BFS.
2. For every (k-1)-tag subset, produce two distinct LEGAL scramble words
   having identical vectors of tagged-edge position+orientation factors.
   These two states can never be distinguished by any sequence of sensor
   outputs, regardless of how actions depend on earlier observations.
3. Every reported k-tag subset has an INJECTIVE factor vector on the entire
   radius-r ball, and each distinct physical factor pair admits a 1/2-turn
   separating experiment (verified in fullcube_sensor_goal_theorem.py).
This gives exact minimum k for this finite family and sensor semantics.
"""
from __future__ import annotations
import collections,hashlib,itertools,json,argparse
from fullcube_goal_info_conflict import A,EDGES
from fullcube_sensor_goal_theorem import SOLVED,turn,factor

def physical_balls():
    visited={SOLVED}
    layers=[[(SOLVED,())]]
    for r in range(1,4):
        after=[]
        for state,word in layers[-1]:
            for action in range(18):
                nxt=turn(state,action)
                if nxt not in visited:
                    visited.add(nxt)
                    after.append((nxt,word+(action,)))
        layers.append(after)
    assert list(map(len,layers))==[1,18,243,3240]
    return layers

def validate_sensor_size(cohort,k,record_collisions):
    signatures=[tuple(factor(state,j) for j in range(12))
                for state,_ in cohort]
    accepted=[];failed=[]
    for tags in itertools.combinations(range(12),k):
        observed={};collision=None
        for index,signature in enumerate(signatures):
            key=tuple(signature[j] for j in tags)
            if key in observed:
                collision=(observed[key],index)
                break
            observed[key]=index
        if collision is None:
            accepted.append(tags)
        elif record_collisions:
            i,j=collision
            failed.append({'tags':list(tags),
                'word1':[A[a] for a in cohort[i][1]],
                'word2':[A[a] for a in cohort[j][1]]})
        else:
            failed.append(None)
    assert len(accepted)+len(failed)==len(list(itertools.combinations(range(12),k)))
    return accepted,failed

def audit(include_all_witnesses=False):
    shells=physical_balls()
    output=[]
    for radius,lo,hi,expected_size,expected_designs in [
        (1,2,3,19,8),(2,7,8,262,42),(3,8,9,3502,8)]:
        cohort=[entry for layer in shells[:radius+1] for entry in layer]
        assert len(cohort)==expected_size
        forbidden,collisions=validate_sensor_size(cohort,lo,True)
        feasible,_=validate_sensor_size(cohort,hi,False)
        assert not forbidden and len(feasible)==expected_designs
        digest=hashlib.sha256(json.dumps(
            collisions,sort_keys=True).encode()).hexdigest()
        result={
          'radius':radius,'physical_source_states':len(cohort),
          'minimum_tagged_edge_orientation_sensors':hi,
          'all_below_threshold_sensor_designs_have_collision':len(collisions),
          'successful_minimal_design_count':len(feasible),
          'first_minimal_design':[''.join(EDGES[j]) for j in feasible[0]],
          'all_minimal_designs':[
              [''.join(EDGES[j]) for j in tags] for tags in feasible],
          'sha256_of_collision_evidence':digest,
          'first_negative_collision':collisions[0],
        }
        if include_all_witnesses:
            result['complete_negative_collision_witnesses']=collisions
        output.append(result)
    assert [r['sha256_of_collision_evidence'] for r in output]==[
        'ab367a3c0c92d5dfa8d3f431ed9d3b06d575c46b77036ce352eb786b10651ec9',
        'a9dd769efa1b84b5f62858878fe088fe4a52828fed2f6d0bf8bd3075d066e09b',
        '53f9ceebc0a7563f14cdd9025454f8384b3880fab5db4bbfd4b9c18f49eed3e8']
    return {'status':'EXACT_FULL54_RADIUS1_2_3_SENSOR_MINIMUM_PASS',
            'source_ball_layers':[1,18,243,3240],
            'goal':'every hidden complete physical cube state eventually SOLVED',
            'readings':'noiseless orientation bit per tagged original edge',
            'results':output,'full_027_deep_geodesic_engine_executed':False,
            'novelty_over_sensor_placement_literature_proven':False}

if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--all-witnesses',action='store_true')
    args=p.parse_args()
    print(json.dumps(audit(args.all_witnesses),indent=2,sort_keys=True))
