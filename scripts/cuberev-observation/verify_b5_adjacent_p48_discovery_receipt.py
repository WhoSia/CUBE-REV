#!/usr/bin/env python3
"""Read and independently physically replay every C++ P48 B5 MITM discovery.

The C++ search is a fresh independent source of nine <=5/<=5 HTM pairs.
This reader does NOT trust the words or supports just because stdout says
WITNESS: each physical original-tag difference is regenerated by Python P48.
"""
import re
from pathlib import Path
from b6_independent_48sticker_goals import EDGE_POSITION, EDGE_POS, CORNERS
from emit_b5_adjacent_p48_discovery_goals import discovery_orbits
from verify_b6_complete_4845_p48 import B5_FOUR_SEEDS, ends, physical_orbit
from verify_b6_negative_19_pairs_p48 import physical_support

def verify(log):
    rows=Path(log).read_text(encoding="utf8").splitlines()
    assert any(re.fullmatch(r"P48_B5_BUILD normalized=\d+ unique=621649",s) for s in rows)
    assert rows[-1]=="DONE positive_orbits=9 of=11"
    groups=discovery_orbits()
    counts={}
    seen={}
    for row in rows:
        match=re.fullmatch(r"WITNESS (\d+) (\d+) \| (.*?) \| (.*?) \| (\d+)",row)
        if not match:continue
        group,target_index,left,right,probes=match.groups()
        i=int(group)
        assert 0<=i<11 and 0<=int(target_index)<11
        assert i not in seen
        assert 1<=int(probes)<=624124
        wanted=ends("DL")|frozenset(EDGE_POSITION[e] for e in groups[i])
        assert physical_support(left,right)==wanted
        assert len(left.split())<=5 and len(right.split())<=5
        seen[i]=(left,right)
    for line in rows:
        match=re.fullmatch(r"ORBIT (\d+) hits=(\d+)",line)
        if match:
            idx,n=map(int,match.groups())
            assert idx not in counts and 0<=idx<11
            counts[idx]=n
    assert len(counts)==11 and len(seen)==9
    assert all(counts[i]==(1 if i in seen else 0) for i in range(11))
    # The geometric pattern and P48 physical witness sources must agree.
    expected={frozenset(pair):physical_orbit(a,b,5,
              ends("DL")|frozenset(EDGE_POSITION[e] for e in pair))
              for pair,a,b in B5_FOUR_SEEDS}
    assert set(expected)=={frozenset(groups[i]) for i in seen}
    physical=set()
    for i,(a,b) in seen.items():
        orbit=physical_orbit(a,b,5,
              ends("DL")|frozenset(EDGE_POSITION[e] for e in groups[i]))
        assert orbit==expected[frozenset(groups[i])]
        assert not physical.intersection(orbit)
        physical.update(orbit)
    assert len(physical)==216
    print("P48_B5_DISCOVERY_RECEIPT_PASS nine genuinely replayed 5+5 HTM pairs / 216 four-tag supports")
    return seen

if __name__=="__main__":
    import sys
    if len(sys.argv)!=2:raise SystemExit("usage: verify_b5_adjacent_p48_discovery_receipt.py CXX_LOG")
    verify(sys.argv[1])
