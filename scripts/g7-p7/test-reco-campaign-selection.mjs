import fs from "node:fs";import os from "node:os";import path from "node:path";import {spawnSync} from "node:child_process";
const d=fs.mkdtempSync(path.join(os.tmpdir(),"g7-p7-select-"));
const rows=[];let id=1;
for(const method of ["CFOP","Roux","ZB","Yau","ZZ"])for(const year of [2014,2018,2022,2026])for(let i=0;i<20;i++)rows.push({id:id++,puzzle:"3x3",method,solver:"S"+(i%13),reconstructor:"R"+(i%7),date:year+"-01-01",index_page:1});
fs.writeFileSync(path.join(d,"rows.jsonl"),rows.map(JSON.stringify).join("\n")+"\n");
const p=spawnSync(process.execPath,["scripts/g7-p7/select-reco-campaign.mjs","--input",path.join(d,"rows.jsonl"),"--out",path.join(d,"out")],{encoding:"utf8"});
if(p.status!==0)throw new Error(p.stderr||p.stdout);
const x=JSON.parse(fs.readFileSync(path.join(d,"out","campaign-manifest.json"),"utf8"));
if(x.total!==40||x.batches.length!==4||x.batches.some(b=>b.records.length!==10))throw new Error("SIZE");
if(new Set(x.records.map(r=>r.source_id)).size!==40)throw new Error("DUP");
console.log("G7_P7_RECO_CAMPAIGN_SELECTION_TEST_PASS");