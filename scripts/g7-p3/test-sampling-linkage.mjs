import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'g7-p3-sample-test-'));
const rows=[];
for(let i=1;i<=120;i++) rows.push({id:i,puzzle:'3x3',result:(5+i/100).toFixed(2),solver:'S'+(i%12),method:i%5===0?'Roux':'CFOP',date:(i%2?'2024':'2025')+'-01-01',competition:i%3?'Comp'+i:'',tags:'',movecount:50,tps:8,reconstructor:'R'+(i%8),index_page:Math.ceil(i/50)});
const input=path.join(dir,'rows.jsonl');fs.writeFileSync(input,rows.map(JSON.stringify).join('\n')+'\n');
const preseal=JSON.parse(fs.readFileSync('g7/p3/preseal.json','utf8'));
preseal.frequency_bands={singleton:[1,1],sparse:[2,9],mid:[10,49],high:[50,199],dominant:[200,null]};
fs.writeFileSync(path.join(dir,'preseal.json'),JSON.stringify(preseal));
const cfg=JSON.parse(fs.readFileSync('g7/p3/sampling-linkage.json','utf8'));cfg.population_estimation.n=16;cfg.coverage_analysis.n=12;fs.writeFileSync(path.join(dir,'cfg.json'),JSON.stringify(cfg));
const out=path.join(dir,'out');
const p=spawnSync(process.execPath,['scripts/g7-p3/materialize-sampling-linkage.mjs','--input',input,'--preseal',path.join(dir,'preseal.json'),'--ontology','g7/p3/method-ontology.json','--config',path.join(dir,'cfg.json'),'--out',out],{encoding:'utf8'});
if(p.status!==0) throw new Error(p.stderr||p.stdout);
const m=JSON.parse(fs.readFileSync(path.join(out,'sampling-manifest.json'),'utf8'));
if(m.population_estimation.selected.length!==16) throw new Error('POP_SAMPLE');
if(m.coverage_analysis.selected.length!==Math.min(12,m.eligible_population.nonempty_strata)) throw new Error('COVERAGE_SAMPLE');
if(m.linkage_support.counts.A_EXACT!==0) throw new Error('EXACT_AUTHORITY');
if(m.authority.bulk_mirror!=='HOLD'&&m.authority.bulk_solve_body_mirror!=='HOLD') throw new Error('BULK_HOLD');
console.log('G7_P3_SAMPLING_LINKAGE_TEST_PASS');
