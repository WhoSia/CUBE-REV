import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import {spawnSync} from "node:child_process";
const d=fs.mkdtempSync(path.join(os.tmpdir(),"g7-p4-sum-"));
const tsv="source_id\tmove_index\trank_before\trank_after\taction_index\tmethod_family\treconstructor\th_before\th_after\tbest_h\tbest_count\tlocal_regret\tdescent\n1\t1\t5\t4\t0\tCFOP\tR\t2\t1\t1\t2\t0\t1\n1\t2\t4\t3\t1\tCFOP\tR\t1\t1\t0\t1\t1\t0\n";
fs.writeFileSync(path.join(d,"p.tsv"),tsv);
fs.writeFileSync(path.join(d,"c.json"),JSON.stringify({transition_counts:{SINGLE_HTM:2},single_htm_fraction:1}));
fs.writeFileSync(path.join(d,"e.json"),JSON.stringify({solve_count:1,replay_status_counts:{SUPPORTED:1},supported_fraction:1,records:[{move_count:2,prefixes:[{event_kind:"ANNOTATION",move_index:1,center_relative_correct_facelets:30,solved_faces:1}]}]}));
const p=spawnSync(process.execPath,["scripts/g7-p4/summarize-policy-geometry.mjs","--pdb-tsv",path.join(d,"p.tsv"),"--cubie-json",path.join(d,"c.json"),"--exact-json",path.join(d,"e.json"),"--out",path.join(d,"o")],{encoding:"utf8"});
if(p.status!==0) throw new Error(p.stderr||p.stdout);
const r=JSON.parse(fs.readFileSync(path.join(d,"o","policy-summary.json"),"utf8"));
if(r.search_alignment.n!==2||r.annotation_geometry.annotation_bearing_solves!==1) throw new Error("SUMMARY");
console.log("G7_P4_POLICY_SUMMARY_TEST_PASS");
